drop function if exists public.get_location_thoughts(uuid, uuid, boolean);

create function public.get_location_thoughts(
  p_location_id uuid,
  p_device_id uuid,
  p_mine_only boolean
)
returns table (
  id uuid,
  category text,
  body text,
  background_type text,
  background_color text,
  font_family text,
  font_size smallint,
  image_url text,
  music_url text,
  created_at timestamptz,
  is_own boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    t.id,
    t.category,
    t.body,
    t.background_type,
    t.background_color,
    t.font_family,
    t.font_size,
    t.image_url,
    t.music_url,
    t.created_at,
    (t.device_id = p_device_id) as is_own
  from public.thoughts t
  where t.location_id = p_location_id
    and t.hidden = false
    and (
      (p_mine_only = true and t.device_id = p_device_id)
      or
      (
        p_mine_only = false
        and exists (
          select 1
          from public.unlocks u
          where u.location_id = p_location_id
            and u.device_id = p_device_id
        )
      )
    )
  order by t.created_at desc;
$$;

revoke all on function public.get_location_thoughts(uuid, uuid, boolean) from public;
grant execute on function public.get_location_thoughts(uuid, uuid, boolean) to anon;

-- SUBURB PROGRESS -----------------------------------------------------------

create or replace function public.get_suburb_progress(p_suburb text)
returns table (
  active_locations bigint,
  total_thoughts bigint,
  unique_contributors bigint,
  successful_unlocks bigint,
  progress double precision
)
language sql
stable
security definer
set search_path = ''
as $$
  with stats as (
    select
      (
        select count(*)
        from public.locations l
        where l.suburb = p_suburb
          and exists (
            select 1
            from public.thoughts t
            where t.location_id = l.id
              and t.hidden = false
          )
      )::bigint as active_locations,
      (
        select count(*)
        from public.thoughts t
        join public.locations l on l.id = t.location_id
        where l.suburb = p_suburb
          and t.hidden = false
      )::bigint as total_thoughts,
      (
        select count(distinct t.device_id)
        from public.thoughts t
        join public.locations l on l.id = t.location_id
        where l.suburb = p_suburb
          and t.hidden = false
      )::bigint as unique_contributors,
      (
        select count(*)
        from public.unlocks u
        join public.locations l on l.id = u.location_id
        where l.suburb = p_suburb
      )::bigint as successful_unlocks
  )
  select
    active_locations,
    total_thoughts,
    unique_contributors,
    successful_unlocks,
    least(
      active_locations / 15.0,
      total_thoughts / 50.0,
      unique_contributors / 30.0,
      successful_unlocks / 50.0,
      1.0
    )::double precision as progress
  from stats;
$$;

revoke all on function public.get_suburb_progress(text) from public;
grant execute on function public.get_suburb_progress(text) to anon;

-- UNLOCK -------------------------------------------------------------------
-- User GPS is constructed in memory, checked, and never stored.

create or replace function public.record_unlock(
  p_device_id uuid,
  p_location_id uuid,
  p_user_lat double precision,
  p_user_lng double precision
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user extensions.geography;
  v_location extensions.geography;
begin
  v_user := extensions.st_setsrid(
    extensions.st_makepoint(p_user_lng, p_user_lat), 4326
  )::extensions.geography;

  select l.geom
    into v_location
  from public.locations l
  where l.id = p_location_id;

  if v_location is null then
    raise exception 'Location not found';
  end if;

  if not extensions.st_dwithin(v_user, v_location, 50) then
    raise exception 'Get closer';
  end if;

  insert into public.unlocks(device_id, location_id)
  values (p_device_id, p_location_id)
  on conflict do nothing;

  return true;
end;
$$;

revoke all on function public.record_unlock(
  uuid, uuid, double precision, double precision
) from public;
grant execute on function public.record_unlock(
  uuid, uuid, double precision, double precision
) to anon;

-- PUBLISH THOUGHT -----------------------------------------------------------
-- Raw Drop and user GPS values are validation-only function parameters. The
-- only persisted coordinate is the privacy-adjusted Safe Anchor (or a nearby
-- existing node selected by the 20m merge).

create or replace function public.is_supported_music_url(p_url text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select
    p_url is null
    or btrim(p_url) = ''
    or btrim(p_url) ~* '^https://open[.]spotify[.]com/track/[a-z0-9]+/?$'
    or btrim(p_url) ~* '^https://music[.]apple[.]com/[a-z]{2}/song/[^/?#[:space:]]+/[0-9]+/?$'
    or btrim(p_url) ~* '^https://music[.]apple[.]com/[a-z]{2}/album/[^/?#[:space:]]+/[0-9]+[?]i=[0-9]+$'
    or btrim(p_url) ~* '^https://music[.]youtube[.]com/watch[?]v=[a-z0-9_-]+$';
$$;

