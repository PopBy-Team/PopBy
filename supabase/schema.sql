create index if not exists thoughts_location_idx
  on public.thoughts(location_id, created_at desc);

create index if not exists thoughts_device_idx
  on public.thoughts(device_id, created_at desc);

create table if not exists public.unlocks (
  device_id uuid not null,
  location_id uuid not null references public.locations(id) on delete cascade,
  unlocked_at timestamptz not null default now(),
  primary key (device_id, location_id)
);

create table if not exists public.reports (
  thought_id uuid not null references public.thoughts(id) on delete cascade,
  device_id uuid not null,
  created_at timestamptz not null default now(),
  primary key (thought_id, device_id)
);

create table if not exists public.dwell_events (
  id bigint generated by default as identity primary key,
  thought_id uuid not null references public.thoughts(id) on delete cascade,
  device_id uuid not null,
  ms integer not null check (ms >= 0 and ms <= 120000),
  created_at timestamptz not null default now()
);

