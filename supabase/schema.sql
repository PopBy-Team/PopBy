drop function if exists public.get_map_locations();
drop function if exists public.get_map_locations(uuid);

create function public.get_map_locations(p_device_id uuid)
returns table (
  location_id uuid,
  suburb text,
  lat double precision,
  lng double precision,
  thought_count bigint,
  dominant_category text,
  latest_at timestamptz,
  is_mine boolean,
  is_unlocked boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    l.id as location_id,
    l.suburb,
    l.lat,
    l.lng,
    count(t.id)::bigint as thought_count,
    (
      select t2.category
      from public.thoughts t2
      where t2.location_id = l.id
        and t2.hidden = false
      group by t2.category
      order by count(*) desc, max(t2.created_at) desc
      limit 1
    ) as dominant_category,
    max(t.created_at) as latest_at,
    bool_or(t.device_id = p_device_id) as is_mine,
    exists (
      select 1
      from public.unlocks u
      where u.location_id = l.id
        and u.device_id = p_device_id
    ) as is_unlocked
  from public.locations l
  join public.thoughts t
    on t.location_id = l.id
   and t.hidden = false
  group by l.id, l.suburb, l.lat, l.lng
  order by latest_at desc;
$$;

revoke all on function public.get_map_locations(uuid) from public;
grant execute on function public.get_map_locations(uuid) to anon;

