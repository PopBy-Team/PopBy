-- REPORT -------------------------------------------------------------------

create or replace function public.report_thought(
  p_device_id uuid,
  p_thought_id uuid
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer;
begin
  insert into public.reports(thought_id, device_id)
  values (p_thought_id, p_device_id)
  on conflict do nothing;

  select count(*)::integer
    into v_count
  from public.reports r
  where r.thought_id = p_thought_id;

  if v_count >= 2 then
    update public.thoughts t
    set hidden = true
    where t.id = p_thought_id;
  end if;

  return v_count;
end;
$$;

revoke all on function public.report_thought(uuid, uuid) from public;
grant execute on function public.report_thought(uuid, uuid) to anon;

-- OWNER DELETE -------------------------------------------------------------

create or replace function public.delete_thought(
  p_device_id uuid,
  p_thought_id uuid
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  delete from public.thoughts t
  where t.id = p_thought_id
    and t.device_id = p_device_id;

  if not found then
    raise exception 'Thought not found';
  end if;

  return true;
end;
$$;

revoke all on function public.delete_thought(uuid, uuid) from public;
grant execute on function public.delete_thought(uuid, uuid) to anon, authenticated;

-- DWELL --------------------------------------------------------------------

create or replace function public.record_dwell(
  p_device_id uuid,
  p_thought_id uuid,
  p_ms integer
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_ms is null or p_ms < 0 or p_ms > 120000 then
    return;
  end if;

  insert into public.dwell_events(thought_id, device_id, ms)
  values (p_thought_id, p_device_id, p_ms);
end;
$$;

revoke all on function public.record_dwell(uuid, uuid, integer) from public;
